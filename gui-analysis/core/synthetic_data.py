def generate_random_synthetic_record(index: int = 1) -> PatientRecord:
    """Generate a randomized synthetic patient record for batch simulation."""
    dept = random.choice([
        "ICU Ward 3", "Cardiology Unit", "Radiology & Imaging",
        "Emergency Care Unit", "Pediatrics Unit"
    ])
    conditions = ["Stable", "Observation", "Post-Op Recovery", "Urgent Review"]
    
    hr = random.randint(60, 120)
    spo2 = random.randint(90, 100)
    sys = random.randint(100, 145)
    dia = random.randint(65, 95)
    temp = round(random.uniform(36.4, 38.5), 1)

    return PatientRecord(
        patient_id=f"SYN-GEN-{index:04d}",
        department=dept,
        condition=random.choice(conditions),
        vitals={
            "heart_rate_bpm": hr,
            "spo2_percent": spo2,
            "blood_pressure": f"{sys}/{dia} mmHg",
            "temp_celsius": temp
        },
        clinical_note=f"Automated telemetric sync #{index} from {dept}. Synthetic academic test frame."
    )
